#include <math.h>

typedef struct { uint8_t b[16]; } blk;

/* ---- AES round: portable table version ------------------------------------------------ */
static uint8_t SBOX[256];
static void sbox_init(void) {              /* multiplicative inverse in GF(2^8), then the affine map */
    uint8_t p = 1, q = 1;
    do {
        p = p ^ (uint8_t)(p << 1) ^ ((p & 0x80) ? 0x1b : 0);
        q ^= q << 1; q ^= q << 2; q ^= q << 4; if (q & 0x80) q ^= 0x09;
        uint8_t x = q ^ (uint8_t)((q << 1) | (q >> 7)) ^ (uint8_t)((q << 2) | (q >> 6))
                    ^ (uint8_t)((q << 3) | (q >> 5)) ^ (uint8_t)((q << 4) | (q >> 4));
        SBOX[p] = x ^ 0x63;
    } while (p != 1);
    SBOX[0] = 0x63;
}
static inline uint8_t xt(uint8_t a) { return (uint8_t)((a << 1) ^ ((a & 0x80) ? 0x1b : 0)); }
/* x86 AESENC(x, k) = MixColumns(ShiftRows(SubBytes(x))) ^ k */
static blk aesenc_portable(blk s, blk k) {
    blk t;
    for (int c = 0; c < 4; c++) for (int r = 0; r < 4; r++) t.b[4 * c + r] = SBOX[s.b[4 * ((c + r) & 3) + r]];
    for (int c = 0; c < 4; c++) {
        uint8_t *col = t.b + 4 * c, a0 = col[0], a1 = col[1], a2 = col[2], a3 = col[3], all = a0 ^ a1 ^ a2 ^ a3;
        col[0] = a0 ^ all ^ xt(a0 ^ a1); col[1] = a1 ^ all ^ xt(a1 ^ a2);
        col[2] = a2 ^ all ^ xt(a2 ^ a3); col[3] = a3 ^ all ^ xt(a3 ^ a0);
    }
    for (int i = 0; i < 16; i++) t.b[i] ^= k.b[i];
    return t;
}

/* ---- hardware paths (optional) -------------------------------------------------------- */
#if !defined(GO_PORTABLE) && defined(__AES__)
#include <wmmintrin.h>
#define IMPL_NAME "x86-aesni"
#define HAVE_HW 1
static inline blk aesenc_hw(blk s, blk k) {
    __m128i a = _mm_loadu_si128((const __m128i *)s.b), b = _mm_loadu_si128((const __m128i *)k.b);
    blk o; _mm_storeu_si128((__m128i *)o.b, _mm_aesenc_si128(a, b)); return o;
}
#elif !defined(GO_PORTABLE) && (defined(__ARM_FEATURE_AES) || defined(__ARM_FEATURE_CRYPTO))
#include <arm_neon.h>
#define IMPL_NAME "arm-neon-aes"
#define HAVE_HW 1
static inline blk aesenc_hw(blk s, blk k) {   /* AESE(x, 0) = SB(SR(x)); AESMC; then ^ k */
    uint8x16_t a = vld1q_u8(s.b), b = vld1q_u8(k.b);
    blk o; vst1q_u8(o.b, veorq_u8(vaesmcq_u8(vaeseq_u8(a, vdupq_n_u8(0))), b)); return o;
}
#else
#define IMPL_NAME "portable"
#define HAVE_HW 0
#endif

#if HAVE_HW
#define aesenc aesenc_hw
#else
#define aesenc aesenc_portable
#endif

static inline blk ld(const uint8_t *p) { blk r; memcpy(r.b, p, 16); return r; }
static inline blk bxor(blk a, blk b) { for (int i = 0; i < 16; i++) a.b[i] ^= b.b[i]; return a; }
static inline uint64_t lo64(blk x) { uint64_t v = 0; for (int i = 7; i >= 0; i--) v = (v << 8) | x.b[i]; return v; }
static inline blk F(blk x) { return aesenc(x, x); }   /* AESENC X,X : the keyless scramble */

/* ---- memHashAES (memhash_amd64.s), class by class ------------------------------------ */
static uint64_t memhash_aes(const uint8_t *ks, const uint8_t *p, uint64_t seed, size_t len) {
    blk x0;
    for (int i = 0; i < 8; i++) x0.b[i] = (uint8_t)(seed >> (8 * i));            /* MOVQ BX, X0 */
    for (int w = 4; w < 8; w++) { x0.b[2 * w] = (uint8_t)len; x0.b[2 * w + 1] = (uint8_t)(len >> 8); }
                                                                                  /* PINSRW $4, CX; PSHUFHW $0 */
    blk x1 = x0;                                                                  /* unscrambled seed */
    x0 = F(bxor(x0, ld(ks)));                                                     /* PXOR aeskeysched; AESENC X0,X0 */
    if (len < 16) {
        if (len == 0) return lo64(F(x0));                                         /* aes0 */
        blk d; memset(d.b, 0, 16); memcpy(d.b, p, len);                           /* masks<> / shifts<>: len bytes */
        d = F(F(F(bxor(d, x0))));                                                 /* final1 */
        return lo64(d);
    }
    if (len == 16) return lo64(F(F(F(bxor(ld(p), x0)))));                         /* aes16 */
    if (len <= 32) {
        blk s1 = F(bxor(x1, ld(ks + 16)));
        blk a = bxor(ld(p), x0), b = bxor(ld(p + len - 16), s1);
        for (int r = 0; r < 3; r++) { a = F(a); b = F(b); }
        return lo64(bxor(a, b));
    }
    if (len <= 64) {
        blk s[4], d[4]; s[0] = x0;
        for (int i = 1; i < 4; i++) s[i] = F(bxor(x1, ld(ks + 16 * i)));
        d[0] = bxor(ld(p), s[0]); d[1] = bxor(ld(p + 16), s[1]);
        d[2] = bxor(ld(p + len - 32), s[2]); d[3] = bxor(ld(p + len - 16), s[3]);
        for (int r = 0; r < 3; r++) for (int i = 0; i < 4; i++) d[i] = F(d[i]);
        d[0] = bxor(d[0], d[2]); d[1] = bxor(d[1], d[3]);
        return lo64(bxor(d[0], d[1]));
    }
    blk s[8], d[8]; s[0] = x0;
    for (int i = 1; i < 8; i++) s[i] = F(bxor(x1, ld(ks + 16 * i)));
    if (len <= 128) {
        for (int i = 0; i < 4; i++) d[i] = bxor(ld(p + 16 * i), s[i]);
        for (int i = 0; i < 4; i++) d[4 + i] = bxor(ld(p + len - 64 + 16 * i), s[4 + i]);
    } else {
        for (int i = 0; i < 8; i++) d[i] = bxor(ld(p + len - 128 + 16 * i), s[i]);  /* last block first */
        size_t blocks = (len - 1) >> 7; const uint8_t *q = p;
        do {
            for (int i = 0; i < 8; i++) d[i] = F(d[i]);                           /* scramble state */
            for (int i = 0; i < 8; i++) d[i] = aesenc(d[i], ld(q + 16 * i));      /* scramble, xor in a block */
            q += 128;
        } while (--blocks);
    }
    for (int r = 0; r < 3; r++) for (int i = 0; i < 8; i++) d[i] = F(d[i]);
    for (int i = 0; i < 4; i++) d[i] = bxor(d[i], d[4 + i]);
    d[0] = bxor(d[0], d[2]); d[1] = bxor(d[1], d[3]);
    return lo64(bxor(d[0], d[1]));
}
/* hash/maphash.Bytes / String / Hash.Sum64: 128-byte chunks chained through memhash */
static uint64_t maphash_bytes(const uint8_t *ks, uint64_t seed, const uint8_t *p, size_t len) {
    uint64_t st = seed;
    while (len > 128) { st = memhash_aes(ks, p, st, 128); p += 128; len -= 128; }
    return len ? memhash_aes(ks, p, st, len) : st;
}

