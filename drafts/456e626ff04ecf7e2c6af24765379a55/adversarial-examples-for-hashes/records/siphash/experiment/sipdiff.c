int main(int argc, char **argv) {
    if (argc >= 2 && !strcmp(argv[1], "selftest")) return selftest();
    if (argc < 7) { fprintf(stderr, "usage: %s <variant 10|11|12|13|24> <W 1|2> <log2 keys> <seed> <mode R|F<hex m0>[,<hex m1>]> <diff-file> [maxdiffs]\n", argv[0]); return 2; }
    int var = atoi(argv[1]), W = atoi(argv[2]), lg = atoi(argv[3]); uint64_t seed = strtoull(argv[4], 0, 0);
    sipfn f = var == 10 ? sip10 : var == 11 ? sip11 : var == 12 ? sip12 : var == 13 ? sip13 : sip24;
    int fixed = argv[5][0] == 'F'; uint64_t mfix[2] = {0, 0};
    if (fixed) { char *p = argv[5] + 1; mfix[0] = strtoull(p, &p, 16); if (*p == ',') mfix[1] = strtoull(p+1, 0, 16); }
    FILE *df = fopen(argv[6], "r"); if (!df) { perror("diff file"); return 2; }
    int maxd = argc >= 8 ? atoi(argv[7]) : 1<<20;
    diff_t *diffs = malloc(sizeof(diff_t) * 20000); int nd = 0; char line[256];
    while (nd < maxd && fgets(line, sizeof line, df)) { if (line[0] == '#' || line[0] == '\n') continue;
        char a[64], b[64], nm[64]; nm[0] = 0; if (sscanf(line, "%63s %63s %47s", a, b, nm) < 2) continue;
        diffs[nd].d[0] = strtoull(a, 0, 16); diffs[nd].d[1] = strtoull(b, 0, 16); snprintf(diffs[nd].name, 48, "%s", nm); nd++; }
    fclose(df);
    stat_t *st = calloc(nd, sizeof(stat_t));
    sm_state = seed ^ 0x5eed0000ULL; for (int i = 0; i < 4; i++) xs[i] = splitmix64();
    uint64_t N = 1ULL << lg;
    for (uint64_t it = 0; it < N; it++) {
        uint64_t k0 = xrand(), k1 = xrand(), m[2], m2[2];
        if (fixed) { m[0] = mfix[0]; m[1] = mfix[1]; } else { m[0] = xrand(); m[1] = xrand(); }
        uint64_t h0 = f(m, W, k0, k1);
        for (int j = 0; j < nd; j++) {
            m2[0] = m[0] ^ diffs[j].d[0]; m2[1] = m[1] ^ diffs[j].d[1];
            uint64_t d = h0 ^ f(m2, W, k0, k1); int pc = __builtin_popcountll(d);
            stat_t *s = &st[j]; s->coll += (d == 0); s->low32 += ((uint32_t)d == 0); s->low16 += ((uint16_t)d == 0); s->popsum += pc; s->hist[pc]++;
        }
    }
    // Output: one line per difference. z = (mean popcount - 32) / (4 / sqrt(N)) is the distinguisher z-score.
    printf("# variant=%d W=%d log2keys=%d seed=%" PRIu64 " mode=%s N=%" PRIu64 "\n", var, W, lg, seed, argv[5], N);
    printf("# d0 d1 name coll low32 low16 meanpop z hist0..8\n");
    for (int j = 0; j < nd; j++) { stat_t *s = &st[j]; double mean = (double)s->popsum / N; double z = (mean - 32.0) / (4.0 / __builtin_sqrt((double)N));
        printf("%016" PRIx64 " %016" PRIx64 " %s %" PRIu64 " %" PRIu64 " %" PRIu64 " %.5f %.2f", diffs[j].d[0], diffs[j].d[1], diffs[j].name, s->coll, s->low32, s->low16, mean, z);
        for (int p = 0; p <= 8; p++) printf(" %" PRIu64, s->hist[p]); printf("\n"); }
    return 0;
}
